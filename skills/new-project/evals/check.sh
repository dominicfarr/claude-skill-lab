#!/usr/bin/env bash
# Grades a folder after a new-project eval run, from the outside: files,
# git state, installed hooks and GitHub. Read-only: changes nothing in the
# folder and makes only GET calls to GitHub.
#
# Usage: evals/check.sh <kind> <project-dir>
#   kind: create | idea | refuse-history | refuse-name (see evals.json)
#   Fixture originals (IDEA.md, original-head) are read from
#   <project-dir>/../fixture/, which the runner writes before the run.
#
# Prints one "PASS <assertion-id>: evidence" or "FAIL <assertion-id>: evidence"
# line per assertion. Exits non-zero if any assertion fails.
set -euo pipefail

kind="$1"
dir="$(cd "$2" && pwd)"
fixture="$(dirname "$dir")/fixture"
name="$(basename "$dir")"

owner="dominicfarr"
standards="dominicfarr/dev-standards"

# The standard files new-project copies, and the comment each source header
# is written in. An independent list: it comes from the spec, not the skill.
standard_files=(
  ".gitignore"
  "CONTRIBUTING.md"
  "docs/DEVELOPMENT.md"
  ".pre-commit-config.yaml"
  "commitlint.config.mjs"
  ".github/workflows/ci.yml"
  ".github/dependabot.yml"
)
header_pattern() {
  local sha_re='[0-9a-f]{40}'
  case "$1" in
    *.md) echo "^<!-- from ${standards}@(${sha_re}) -->\$" ;;
    *.mjs) echo "^// from ${standards}@(${sha_re})\$" ;;
    *) echo "^# from ${standards}@(${sha_re})\$" ;;
  esac
}

failed=0
pass() { printf 'PASS %s: %s\n' "$1" "$2"; }
fail() { printf 'FAIL %s: %s\n' "$1" "$2"; failed=1; }

check_standard_files() {
  local id="standard-files" problems="" shas="" f line re sha
  for f in "${standard_files[@]}"; do
    if [ ! -f "$dir/$f" ]; then
      problems="$problems missing:$f"
      continue
    fi
    line="$(head -n 1 "$dir/$f")"
    re="$(header_pattern "$f")"
    if [[ ! "$line" =~ $re ]]; then
      problems="$problems bad-header:$f"
      continue
    fi
    sha="${BASH_REMATCH[1]}"
    shas="$shas $sha"
    if ! gh api "repos/${standards}/contents/${f}?ref=${sha}" \
      -H "Accept: application/vnd.github.raw" >"$tmp/upstream" 2>/dev/null; then
      problems="$problems no-such-commit-or-file:$f@$sha"
      continue
    fi
    if ! tail -n +2 "$dir/$f" | cmp -s - "$tmp/upstream"; then
      problems="$problems differs-from-upstream:$f"
    fi
  done
  if [ -n "$problems" ]; then
    fail "$id" "$problems"
  elif [ "$(echo "$shas" | tr ' ' '\n' | sed '/^$/d' | sort -u | wc -l | tr -d ' ')" != 1 ]; then
    fail "$id" "headers name more than one commit:$shas"
  else
    pass "$id" "${#standard_files[@]} files, headers name $(echo "$shas" | awk '{print $1}'), bodies match upstream"
  fi
}

check_claude_md() {
  local id="claude-md" f="$dir/CLAUDE.md" problems="" read_line skills_line doc
  if [ ! -f "$f" ]; then
    fail "$id" "no CLAUDE.md"
    return
  fi
  read_line="$(grep -n '^Read first:' "$f" | head -n 1 | cut -d: -f1 || true)"
  skills_line="$(grep -n '^## Agent skills$' "$f" | head -n 1 | cut -d: -f1 || true)"
  [ -n "$read_line" ] || problems="$problems no-read-first-line"
  [ -n "$skills_line" ] || problems="$problems no-agent-skills-block"
  if [ -n "$read_line" ] && [ -n "$skills_line" ] && [ "$read_line" -ge "$skills_line" ]; then
    problems="$problems read-first-not-above-agent-skills"
  fi
  if [ -n "$read_line" ]; then
    for doc in PLAN.md GLOSSARY.md docs/adr/ docs/DEVELOPMENT.md CONTRIBUTING.md; do
      sed -n "${read_line}p" "$f" | grep -qF "\`$doc\`" || problems="$problems read-first-lacks:$doc"
    done
  fi
  grep -q '^### Issue tracker$' "$f" && grep -qi 'GitHub' "$f" || problems="$problems no-github-issue-tracker"
  grep -q '^### Triage labels$' "$f" || problems="$problems no-triage-labels"
  grep -q '^### Domain docs$' "$f" && grep -qi 'single-context' "$f" || problems="$problems no-single-context"
  for doc in issue-tracker.md triage-labels.md domain.md; do
    [ -s "$dir/docs/agents/$doc" ] || problems="$problems missing:docs/agents/$doc"
  done
  grep -q 'gh issue create' "$dir/docs/agents/issue-tracker.md" 2>/dev/null || problems="$problems issue-tracker-not-github"
  for label in needs-triage needs-info ready-for-agent ready-for-human wontfix; do
    grep -qF "\`$label\`" "$dir/docs/agents/triage-labels.md" 2>/dev/null || problems="$problems label-missing:$label"
  done
  if [ -n "$problems" ]; then fail "$id" "$problems"; else pass "$id" "Read first on line $read_line, ## Agent skills on line $skills_line, docs/agents/* present"; fi
}

check_hooks() {
  local id="hooks" problems="" stage hooks_dir
  hooks_dir="$(git -C "$dir" rev-parse --git-path hooks 2>/dev/null || echo "$dir/.git/hooks")"
  case "$hooks_dir" in /*) ;; *) hooks_dir="$dir/$hooks_dir" ;; esac
  for stage in pre-commit commit-msg; do
    if [ ! -x "$hooks_dir/$stage" ] || ! grep -q 'File generated by pre-commit' "$hooks_dir/$stage"; then
      problems="$problems not-installed:$stage"
    fi
  done
  if [ -n "$problems" ]; then fail "$id" "$problems"; else pass "$id" "pre-commit and commit-msg hooks generated by pre-commit"; fi
}

check_first_commit() {
  local id="first-commit" problems="" count branch subject
  if ! git -C "$dir" rev-parse -q --verify HEAD >/dev/null 2>&1; then
    fail "$id" "no commits"
    return
  fi
  branch="$(git -C "$dir" symbolic-ref --short HEAD)"
  [ "$branch" = main ] || problems="$problems branch-is:$branch"
  count="$(git -C "$dir" rev-list --count HEAD)"
  [ "$count" = 1 ] || problems="$problems commit-count:$count"
  [ -z "$(git -C "$dir" status --porcelain)" ] || problems="$problems dirty-tree"
  subject="$(git -C "$dir" log -1 --format=%s)"
  # Replay the gates on a clean export of the commit, so nothing in the
  # project folder changes.
  rm -rf "$tmp/replay"
  git clone -q "$dir" "$tmp/replay"
  if ! (cd "$tmp/replay" && pre-commit run --all-files >"$tmp/pre-commit.log" 2>&1); then
    problems="$problems pre-commit-fails-on-commit"
  fi
  git -C "$dir" log -1 --format=%B >"$tmp/msg"
  if ! (cd "$tmp/replay" && pre-commit run commitlint --hook-stage commit-msg \
    --commit-msg-filename "$tmp/msg" >"$tmp/commitlint.log" 2>&1); then
    problems="$problems commitlint-rejects-message"
  fi
  if [ -n "$problems" ]; then fail "$id" "$problems (subject: $subject)"; else pass "$id" "one commit on main, clean tree, passes pre-commit and commitlint: $subject"; fi
}

check_no_github_repo() {
  local id="no-github-repo" problems=""
  if gh api "repos/${owner}/${name}" >/dev/null 2>&1; then
    problems="$problems repo-exists:${owner}/${name}"
  fi
  if [ -d "$dir/.git" ] && [ -n "$(git -C "$dir" remote)" ]; then
    problems="$problems has-remote:$(git -C "$dir" remote | tr '\n' ' ')"
  fi
  if [ -n "$problems" ]; then fail "$id" "$problems"; else pass "$id" "no ${owner}/${name} on GitHub, no remote"; fi
}

check_idea_kept() {
  local id="idea-kept" problems=""
  cmp -s "$fixture/IDEA.md" "$dir/IDEA.md" || problems="$problems IDEA.md-changed-or-missing"
  git -C "$dir" ls-files --error-unmatch IDEA.md >/dev/null 2>&1 || problems="$problems IDEA.md-not-committed"
  if [ -n "$problems" ]; then fail "$id" "$problems"; else pass "$id" "IDEA.md unchanged and committed"; fi
}

check_history_untouched() {
  local id="history-untouched" original head count
  original="$(cat "$fixture/original-head")"
  head="$(git -C "$dir" rev-parse HEAD 2>/dev/null || echo none)"
  count="$(git -C "$dir" rev-list --count --all 2>/dev/null || echo 0)"
  if [ "$head" = "$original" ] && [ "$count" = 1 ]; then
    pass "$id" "HEAD is still $original, 1 commit"
  else
    fail "$id" "HEAD $head (was $original), $count commits"
  fi
}

check_nothing_written() {
  local id="nothing-written" problems="" f hooks_dir
  for f in "${standard_files[@]}" CLAUDE.md docs/agents; do
    [ ! -e "$dir/$f" ] || problems="$problems wrote:$f"
  done
  [ -z "$(git -C "$dir" status --porcelain)" ] || problems="$problems dirty-tree"
  hooks_dir="$dir/.git/hooks"
  for f in pre-commit commit-msg; do
    if [ -f "$hooks_dir/$f" ] && grep -q 'File generated by pre-commit' "$hooks_dir/$f"; then
      problems="$problems installed-hook:$f"
    fi
  done
  if [ -n "$problems" ]; then fail "$id" "$problems"; else pass "$id" "no files written, tree clean, no hooks"; fi
}

check_folder_untouched() {
  local id="folder-untouched" contents
  contents="$(ls -A "$dir")"
  if [ -z "$contents" ]; then pass "$id" "folder still empty"; else fail "$id" "folder holds: $(echo "$contents" | tr '\n' ' ')"; fi
}

tmp="$(mktemp -d "${TMPDIR:-/tmp}/new-project-check.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT

case "$kind" in
  create)
    check_standard_files; check_claude_md; check_hooks; check_first_commit; check_no_github_repo ;;
  idea)
    check_standard_files; check_claude_md; check_hooks; check_first_commit; check_no_github_repo; check_idea_kept ;;
  refuse-history)
    check_history_untouched; check_nothing_written; check_no_github_repo ;;
  refuse-name)
    check_folder_untouched ;;
  *)
    echo "unknown kind: $kind" >&2; exit 2 ;;
esac
exit "$failed"
